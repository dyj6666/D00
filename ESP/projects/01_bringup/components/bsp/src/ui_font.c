const uint16_t bsp_ui_cjk_count = 88;

const bsp_ui_glyph_t *bsp_ui_font_lookup(uint32_t codepoint)
{
    if (codepoint >= 0x20U && codepoint <= 0x7EU) {
        return &bsp_ui_ascii[codepoint - 0x20U];
    }
    for (uint16_t i = 0; i < bsp_ui_cjk_count; i++) {
        if (bsp_ui_cjk[i].codepoint == codepoint) {
            return &bsp_ui_cjk[i];
        }
    }
    return NULL;
}
